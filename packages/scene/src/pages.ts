/**
 * Extra export pages, built as ordinary scenes so every exporter (PDF, PowerPoint, draw.io, SVG)
 * renders them with no format-specific code (EXP-03, PCK-03, DEC-051):
 *
 *   buildConditionsScene(def, …)   readable condition list on its own 16:9 page; on wide processes
 *                                  the list under the diagram shrinks with it and becomes unreadable
 *   buildCoverScene(pack)          pack cover: title, date, contents with a health summary per definition
 */
import type { ProcessDefinition } from '@bpmap/model';
import { nodeTokens, semantic, type Theme } from '@bpmap/design-tokens';
import type { Scene, SceneItem } from './index.ts';
import { wrapText } from './text.ts';

const PAGE_W = 1600;
const PAGE_H = 900; // 16:9; pages grow taller when the content needs it
const M = 64;
const FOOTER = 'Generated by BPMap · Independent product, not affiliated with Workday, Inc.';

const defName = (d: { process: string; variant: string }) => (d.variant ? `${d.process} (${d.variant})` : d.process);

export function buildConditionsScene(def: ProcessDefinition, theme: Theme = 'light', conditionText: Readonly<Record<string, string>> = {}): Scene | null {
  if (!def.conditions.length) return null;
  const s = semantic[theme];
  const tk = nodeTokens(theme);
  const items: SceneItem[] = [
    {
      t: 'group',
      role: 'header',
      children: [
        { t: 'text', x: M, y: M + 10, text: `${defName(def)} · Conditions`, size: 30, weight: 700, fill: s.primary },
        { t: 'text', x: M, y: M + 40, text: 'A step runs only when its conditions are true. Badges match the Cn tags on the diagram.', size: 15, weight: 400, fill: s['text-muted'] },
      ],
    },
  ];
  const orderOf = new Map<string, string>(def.steps.map((st) => [st.id, st.order]));
  const cols = def.conditions.length > 8 ? 2 : 1;
  const colW = (PAGE_W - 2 * M - (cols - 1) * 48) / cols;
  const textW = colW - 64;
  const top = M + 92;
  const colY = Array.from({ length: cols }, () => top);
  const per = Math.ceil(def.conditions.length / cols);
  const list: SceneItem[] = [];
  def.conditions.forEach((c, i) => {
    const col = Math.floor(i / per);
    const x = M + col * (colW + 48);
    let y = colY[col]!;
    const plain = conditionText[c.id];
    const lines = wrapText(plain ?? c.text, textW, 17, 500, 3);
    const original = plain ? wrapText(`Workday: ${c.text}`, textW, 13, 400, 2) : [];
    list.push({ t: 'rect', x, y: y - 16, w: 46, h: 22, r: 11, fill: tk.conditionBadge.bg, stroke: tk.conditionalBorder, strokeWidth: 1.25 });
    list.push({ t: 'text', x: x + 23, y: y, text: c.id, size: 13, weight: 700, fill: tk.conditionBadge.text, anchor: 'middle', mono: true });
    for (const ln of lines) {
      list.push({ t: 'text', x: x + 62, y, text: ln, size: 17, weight: 500, fill: s.text });
      y += 23;
    }
    for (const ln of original) {
      list.push({ t: 'text', x: x + 62, y: y - 2, text: ln, size: 13, weight: 400, fill: s['text-secondary'] });
      y += 18;
    }
    const where = [...new Set(c.stepIds.map((id) => orderOf.get(id)).filter(Boolean))].join(', ');
    list.push({ t: 'text', x: x + 62, y: y - 2, text: `${c.workdayOwned ? 'Workday owned' : 'Custom: re-check after each Workday release'}${where ? ` · step ${where}` : ''}`, size: 13, weight: 400, fill: s['text-muted'] });
    colY[col] = y + 30;
  });
  items.push({ t: 'group', role: 'conditions', children: list });
  const height = Math.max(PAGE_H, Math.ceil(Math.max(...colY) + 40 + M));
  items.push({ t: 'group', role: 'footer', children: [{ t: 'text', x: M, y: height - M / 2, text: FOOTER, size: 12, weight: 400, fill: s['text-muted'] }] });
  return { width: PAGE_W, height, background: s.surface, items };
}

export interface CoverEntry {
  name: string;
  view: string;
  summary: string;
  health: { critical: number; warning: number; info: number };
}

export function buildCoverScene(pack: { title: string; date: string; entries: CoverEntry[] }, theme: Theme = 'light'): Scene {
  const s = semantic[theme];
  const items: SceneItem[] = [
    {
      t: 'group',
      role: 'header',
      children: [
        { t: 'rect', x: 0, y: 0, w: PAGE_W, h: 12, fill: s.primary },
        { t: 'text', x: M, y: M + 60, text: pack.title, size: 44, weight: 700, fill: s.primary },
        { t: 'text', x: M, y: M + 100, text: `${pack.entries.length} business process definition${pack.entries.length === 1 ? '' : 's'} · ${pack.date}`, size: 18, weight: 400, fill: s['text-muted'] },
      ],
    },
  ];
  const rows: SceneItem[] = [];
  const X = { n: M, name: M + 48, view: M + 760, health: M + 1000 };
  let y = M + 180;
  rows.push({ t: 'text', x: X.name, y, text: 'CONTENTS', size: 13, weight: 800, fill: s['text-muted'], letterSpacing: 1.5 });
  rows.push({ t: 'text', x: X.view, y, text: 'VIEW', size: 13, weight: 800, fill: s['text-muted'], letterSpacing: 1.5 });
  rows.push({ t: 'text', x: X.health, y, text: 'HEALTH (CRITICAL · WARNING · INFO)', size: 13, weight: 800, fill: s['text-muted'], letterSpacing: 1.5 });
  y += 16;
  pack.entries.forEach((e, i) => {
    rows.push({ t: 'path', points: [[M, y], [PAGE_W - M, y]], stroke: s.border, width: 1 });
    y += 34;
    rows.push({ t: 'text', x: X.n, y, text: String(i + 1), size: 18, weight: 700, fill: s['text-muted'] });
    const nameLines = wrapText(e.name, X.view - X.name - 24, 18, 600, 2);
    nameLines.forEach((ln, j) => rows.push({ t: 'text', x: X.name, y: y + j * 24, text: ln, size: 18, weight: 600, fill: s.text }));
    rows.push({ t: 'text', x: X.name, y: y + nameLines.length * 24 - 2, text: e.summary, size: 13, weight: 400, fill: s['text-muted'] });
    rows.push({ t: 'text', x: X.view, y, text: e.view, size: 16, weight: 400, fill: s['text-secondary'] });
    const h = e.health;
    const healthText = h.critical + h.warning + h.info === 0 ? 'No findings' : `${h.critical} · ${h.warning} · ${h.info}`;
    rows.push({ t: 'text', x: X.health, y, text: healthText, size: 16, weight: h.critical ? 700 : 400, fill: h.critical ? s.danger : s['text-secondary'] });
    y += nameLines.length * 24 + 12;
  });
  rows.push({ t: 'path', points: [[M, y], [PAGE_W - M, y]], stroke: s.border, width: 1 });
  items.push({ t: 'group', role: 'legend', children: rows });
  const height = Math.max(PAGE_H, Math.ceil(y + 60 + M));
  items.push({ t: 'group', role: 'footer', children: [{ t: 'text', x: M, y: height - M / 2, text: FOOTER, size: 12, weight: 400, fill: s['text-muted'] }] });
  return { width: PAGE_W, height, background: s.surface, items };
}
