/**
 * Scene → PowerPoint with NATIVE, editable shapes (EXP-03): rectangles, diamonds, circles,
 * connectors (one line per segment, arrowhead on the last) and text boxes. One slide per scene.
 * The slide size follows the largest scene, capped at PowerPoint's 56-inch maximum (DEC-045).
 */
import PptxGenJS from 'pptxgenjs';
import type { Scene } from '@bpmap/scene';
import { estimateTextWidth, flatten } from './flatten.ts';

const MAX_IN = 56;
const PX_PER_IN = 96;
const col = (c: string | undefined) => (c && c !== 'none' ? c.replace('#', '').toUpperCase() : undefined);
const dashType = (d?: number[]) => (d?.length ? ('dash' as const) : ('solid' as const));

export interface PptxSlideSpec {
  title: string;
  scene: Scene;
}

/** Returns a configured presentation; call `.write({ outputType })` to get bytes. */
export function buildPptx(slides: PptxSlideSpec[], meta: { title: string; company?: string } = { title: 'BPMap' }) {
  const pptx = new PptxGenJS();
  const scaleOf = (s: Scene) => Math.min(1 / PX_PER_IN, MAX_IN / s.width, MAX_IN / s.height); // inches per px
  const layoutW = Math.max(...slides.map((s) => s.scene.width * scaleOf(s.scene)), 1);
  const layoutH = Math.max(...slides.map((s) => s.scene.height * scaleOf(s.scene)), 1);
  pptx.defineLayout({ name: 'BPMAP', width: layoutW, height: layoutH });
  pptx.layout = 'BPMAP';
  pptx.title = meta.title;
  pptx.company = meta.company ?? 'Generated by BPMap (independent; not affiliated with Workday, Inc.)';

  for (const spec of slides) {
    const { scene } = spec;
    const k = scaleOf(scene);
    const X = (v: number) => v * k;
    const pt = (pxSize: number) => Math.max(1, pxSize * k * 72);
    const slide = pptx.addSlide();
    slide.background = { color: col(scene.background) ?? 'FFFFFF' };
    for (const p of flatten(scene)) {
      if (p.t === 'rect') {
        slide.addShape(p.r ? pptx.ShapeType.roundRect : pptx.ShapeType.rect, {
          x: X(p.x), y: X(p.y), w: Math.max(X(p.w), 0.001), h: Math.max(X(p.h), 0.001),
          fill: { color: col(p.fill) ?? 'FFFFFF' },
          line: p.stroke ? { color: col(p.stroke)!, width: pt(p.strokeWidth ?? 1), dashType: dashType(p.dash) } : { type: 'none' },
          ...(p.r ? { rectRadius: Math.min(0.5, (p.r ?? 0) / Math.max(1, Math.min(p.w, p.h))) } : {}),
        });
      } else if (p.t === 'circle') {
        slide.addShape(pptx.ShapeType.ellipse, {
          x: X(p.cx - p.r), y: X(p.cy - p.r), w: X(2 * p.r), h: X(2 * p.r),
          fill: { color: col(p.fill) ?? 'FFFFFF' },
          line: p.stroke ? { color: col(p.stroke)!, width: pt(p.strokeWidth ?? 1) } : { type: 'none' },
        });
      } else if (p.t === 'poly') {
        const xs = p.points.map((q) => q[0]);
        const ys = p.points.map((q) => q[1]);
        slide.addShape(pptx.ShapeType.diamond, {
          x: X(Math.min(...xs)), y: X(Math.min(...ys)), w: X(Math.max(...xs) - Math.min(...xs)), h: X(Math.max(...ys) - Math.min(...ys)),
          fill: { color: col(p.fill) ?? 'FFFFFF' },
          line: p.stroke ? { color: col(p.stroke)!, width: pt(p.strokeWidth ?? 1) } : { type: 'none' },
        });
      } else if (p.t === 'text') {
        const w = estimateTextWidth(p.text, p.size, p.weight) * 1.12 + 4;
        const h = p.size * 1.4;
        const x = p.anchor === 'middle' ? p.x - w / 2 : p.anchor === 'end' ? p.x - w : p.x;
        slide.addText(p.text, {
          x: X(x), y: X(p.y - p.size * 1.1), w: X(w), h: X(h),
          fontSize: pt(p.size), bold: p.weight >= 600, color: col(p.fill), fontFace: p.mono ? 'Consolas' : 'Arial',
          align: p.anchor === 'middle' ? 'center' : p.anchor === 'end' ? 'right' : 'left', valign: 'middle', margin: 0, fit: 'none', wrap: false,
        });
      } else {
        p.points.slice(1).forEach(([x2, y2], i) => {
          const [x1, y1] = p.points[i]!;
          const last = i === p.points.length - 2;
          slide.addShape(pptx.ShapeType.line, {
            x: X(Math.min(x1, x2)), y: X(Math.min(y1, y2)), w: X(Math.abs(x2 - x1)), h: X(Math.abs(y2 - y1)),
            flipH: x2 < x1, flipV: y2 < y1,
            line: { color: col(p.stroke)!, width: pt(p.width), dashType: dashType(p.dash), ...(last && p.arrow ? { endArrowType: 'triangle' as const } : {}) },
          });
        });
      }
    }
    slide.addNotes(`${spec.title}. Generated by BPMap from a Workday business process definition. Every box and line is an editable shape.`);
  }
  return pptx;
}
